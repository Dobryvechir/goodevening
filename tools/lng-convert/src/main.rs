//! One-time converter: `far/farlang.templ.m4` → `assets/lang/*.lng` + `messages.ids`.
//!
//! Usage: `lng-convert <path/to/farlang.templ.m4> <out-dir>`
//!
//! The template lists the languages, then every message id followed by one
//! string per language (in the declared order). Product names are rebranded
//! ("Far Manager" → "Goodevening Manager", "Far" → "gm").

use regex::Regex;
use std::fmt::Write as _;
use std::{env, fs, path::Path, process::ExitCode};

fn main() -> ExitCode {
    let args: Vec<String> = env::args().collect();
    if args.len() != 3 {
        eprintln!("usage: lng-convert <farlang.templ.m4> <out-dir>");
        return ExitCode::FAILURE;
    }
    match run(Path::new(&args[1]), Path::new(&args[2])) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("lng-convert: {e}");
            ExitCode::FAILURE
        }
    }
}

struct Lang {
    file: String,
    name: String,
    descr: String,
}

fn run(src: &Path, out: &Path) -> Result<(), String> {
    let text = fs::read_to_string(src).map_err(|e| format!("{}: {e}", src.display()))?;
    let text = text.trim_start_matches('\u{feff}');
    let mut lines = text.lines().filter(|l| !l.starts_with('#') && !l.starts_with("m4_") && !l.trim().is_empty());

    // Header: hpp name, language count, languages, enum name.
    let _hpp = lines.next().ok_or("missing hpp name")?;
    let mut count: usize = 0;
    for l in lines.by_ref() {
        if l.starts_with("m4_") {
            continue;
        }
        count = l.trim().parse().map_err(|_| format!("bad language count: {l}"))?;
        break;
    }
    let lang_re = Regex::new(r#"^(\S+)\s+(\S+)\s+"(.*)"$"#).unwrap();
    let mut langs = Vec::new();
    for _ in 0..count {
        let l = lines.next().ok_or("missing language line")?;
        let c = lang_re.captures(l).ok_or_else(|| format!("bad language line: {l}"))?;
        langs.push(Lang { file: c[1].replacen("Far", "Gm", 1), name: c[2].to_string(), descr: c[3].to_string() });
    }

    let id_re = Regex::new(r"^M[A-Za-z0-9_]+$").unwrap();
    let mut ids: Vec<String> = Vec::new();
    let mut tables: Vec<Vec<String>> = vec![Vec::new(); count];
    let mut current: Option<(String, Vec<String>)> = None;
    let flush = |cur: &mut Option<(String, Vec<String>)>, ids: &mut Vec<String>, tables: &mut Vec<Vec<String>>| -> Result<(), String> {
        if let Some((id, strings)) = cur.take() {
            if strings.len() != tables.len() {
                return Err(format!("{id}: expected {} strings, got {}", tables.len(), strings.len()));
            }
            for (t, s) in tables.iter_mut().zip(strings) {
                t.push(s);
            }
            ids.push(id);
        }
        Ok(())
    };
    for l in lines {
        if l.starts_with("enum:") || l.starts_with("l:") || l.starts_with("h:") || l.starts_with("he:") {
            continue;
        }
        if id_re.is_match(l) {
            flush(&mut current, &mut ids, &mut tables)?;
            current = Some((l.to_string(), Vec::new()));
            continue;
        }
        let s = l.strip_prefix("upd:").unwrap_or(l);
        if s.starts_with('"')
            && let Some((_, v)) = current.as_mut()
        {
            v.push(rebrand(s));
        }
    }
    flush(&mut current, &mut ids, &mut tables)?;

    fs::create_dir_all(out).map_err(|e| e.to_string())?;
    let mut idfile = String::from("# Generated by tools/lng-convert from far/farlang.templ.m4. One message id per line.\n");
    for id in &ids {
        idfile.push_str(id);
        idfile.push('\n');
    }
    fs::write(out.join("messages.ids"), idfile).map_err(|e| e.to_string())?;

    let mut index = String::from("# file name, language name, language description\n");
    for (lang, table) in langs.iter().zip(&tables) {
        let mut s = String::new();
        let _ = writeln!(s, ".Language={},{}", lang.name, lang.descr);
        let _ = writeln!(s, "// Goodevening Manager language file (generated by tools/lng-convert)");
        for (id, msg) in ids.iter().zip(table) {
            let _ = writeln!(s, "//[{id}]\n{msg}");
        }
        fs::write(out.join(&lang.file), s).map_err(|e| e.to_string())?;
        let _ = writeln!(index, "{} {} \"{}\"", lang.file, lang.name, lang.descr);
    }
    fs::write(out.join("languages.lst"), index).map_err(|e| e.to_string())?;
    println!("{} messages × {} languages written to {}", ids.len(), langs.len(), out.display());
    Ok(())
}

/// Product-name substitution shared by the converters.
pub fn rebrand(s: &str) -> String {
    let s = s
        .replace("Far Manager", "Goodevening Manager")
        .replace("FarMenu.ini", "GmMenu.ini")
        .replace("far:config", "gm:config")
        .replace("far:about", "gm:about")
        .replace("Far.exe", "gm")
        .replace("far.exe", "gm");
    // Standalone word "Far" (not "Far Group", the copyright holder) → "gm".
    let word = Regex::new(r"\bFar\b").unwrap();
    let mut out = String::with_capacity(s.len());
    let mut last = 0;
    for m in word.find_iter(&s) {
        out.push_str(&s[last..m.start()]);
        if s[m.end()..].starts_with(" Group") {
            out.push_str("Far");
        } else {
            out.push_str("gm");
        }
        last = m.end();
    }
    out.push_str(&s[last..]);
    out
}
