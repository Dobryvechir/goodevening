//! One-time converter: `far/palette.cpp` → `crates/gm-term/src/palette_gen.rs`.
//!
//! Usage: `palette-convert <palette.cpp> <out.rs>`

use regex::Regex;
use std::fmt::Write as _;
use std::{env, fs, process::ExitCode};

fn main() -> ExitCode {
    let args: Vec<String> = env::args().collect();
    if args.len() != 3 {
        eprintln!("usage: palette-convert <palette.cpp> <out.rs>");
        return ExitCode::FAILURE;
    }
    let Ok(src) = fs::read_to_string(&args[1]) else {
        eprintln!("palette-convert: cannot read {}", args[1]);
        return ExitCode::FAILURE;
    };
    let re = Regex::new(r#"\{L"([A-Za-z.]+)"sv,\s*([A-Z_|:a-z]+),\s*\},\s*//\s*COL_([A-Z0-9_]+)"#).unwrap();
    let mut rows = Vec::new();
    for c in re.captures_iter(&src) {
        let name = c[1].to_string();
        let ident: String = name.split('.').collect();
        let color = &c[2];
        let (fg, bg) = if color.contains("Default") {
            ("Default".to_string(), "Default".to_string())
        } else {
            let mut fg = "Black".to_string();
            let mut bg = "Black".to_string();
            for part in color.split('|') {
                if let Some(f) = part.strip_prefix("F_") {
                    fg = camel(f);
                } else if let Some(b) = part.strip_prefix("B_") {
                    bg = camel(b);
                }
            }
            (fg, bg)
        };
        rows.push((ident, name, fg, bg));
    }
    let mut out = String::from(
        "// Generated by tools/palette-convert from far/palette.cpp. Do not edit by hand.\n\
         use crate::palette::{C16, C16::*};\n\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n#[repr(u16)]\npub enum PaletteId {\n",
    );
    for (ident, name, _, _) in &rows {
        let _ = writeln!(out, "    /// `{name}`\n    {ident},");
    }
    out.push_str("}\n\n");
    let _ = writeln!(out, "pub const PALETTE_COUNT: usize = {};\n", rows.len());
    out.push_str("/// (setting name, default foreground, default background), indexed by `PaletteId`.\n");
    let _ = writeln!(out, "pub const DEFAULTS: [(&str, C16, C16); {}] = [", rows.len());
    for (_, name, fg, bg) in &rows {
        let _ = writeln!(out, "    (\"{name}\", {fg}, {bg}),");
    }
    out.push_str("];\n\npub const ALL: [PaletteId; PALETTE_COUNT] = [\n");
    for (ident, _, _, _) in &rows {
        let _ = writeln!(out, "    PaletteId::{ident},");
    }
    out.push_str("];\n");
    if let Err(e) = fs::write(&args[2], out) {
        eprintln!("palette-convert: {e}");
        return ExitCode::FAILURE;
    }
    println!("{} palette entries written", rows.len());
    ExitCode::SUCCESS
}

fn camel(s: &str) -> String {
    s.split('_')
        .map(|w| {
            let w = w.to_ascii_lowercase();
            let mut c = w.chars();
            match c.next() {
                Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}
